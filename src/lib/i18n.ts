const DICTS: Record<Language, Dict> = {
  en,
  ru,
  uk,
  de,
  es,
  fr,
  pt,
  it,
  zh,
  ja,
  hi,
  ar,
  bn,
  id: idDict,
  tr,
};

/** Exposed for tooling (tests / audits that compare key sets across languages). */
export const DICTS_FOR_TESTS = DICTS;

export function t(language: Language, key: string, fallback?: string): string {
  return DICTS[language]?.[key] ?? en[key] ?? fallback ?? key;
}

export function isLanguage(value: unknown): value is Language {
  return typeof value === "string" && LANGUAGES.some((l) => l.id === value);
}
